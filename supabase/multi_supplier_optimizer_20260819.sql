create or replace function public.get_launch_cron_status()
returns table(jobname text, schedule text, active boolean)
language sql stable security definer
set search_path = pg_catalog, public, cron
as $$
  select j.jobname::text, j.schedule::text, j.active
  from cron.job as j
  where j.jobname in ('aliexpress-catalog-hourly','supplier-optimizer-hourly','cj-sourcing-hourly','cj-catalog-hourly','cj-sourcing-daily-retry','cj-orders-every-30m')
  order by j.jobname;
$$;
revoke all on function public.get_launch_cron_status() from public, anon, authenticated;
grant execute on function public.get_launch_cron_status() to service_role;

do $$
declare existing_job bigint;
begin
  select jobid into existing_job from cron.job where jobname = 'supplier-optimizer-hourly' limit 1;
  if existing_job is not null then perform cron.unschedule(existing_job); end if;
end $$;

select cron.schedule(
  'supplier-optimizer-hourly',
  '25 * * * *',
  $job$
  select net.http_get(
    url := 'https://aluf-hakelim-v2-ready.vercel.app/api/supplier-optimizer-worker',
    params := '{}'::jsonb,
    headers := jsonb_build_object('Accept','application/json','x-cj-worker-token',(select decrypted_secret from vault.decrypted_secrets where name='cj_worker_token' limit 1)),
    timeout_milliseconds := 60000
  );
  $job$
);
