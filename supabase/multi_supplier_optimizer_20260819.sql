create or replace function public.touch_supplier_offer_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
revoke execute on function public.touch_supplier_offer_updated_at() from public, anon, authenticated;
drop trigger if exists supplier_offers_touch_updated_at on public.supplier_offers;
create trigger supplier_offers_touch_updated_at
before update on public.supplier_offers
for each row execute function public.touch_supplier_offer_updated_at();

