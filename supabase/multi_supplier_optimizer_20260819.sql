-- Generic multi-supplier quote store and safe optimizer settings.
-- Apply after the earlier supplier and fulfillment migrations.

alter table public.site_settings
  add column if not exists supplier_optimizer_enabled boolean not null default false,
  add column if not exists supplier_quote_ttl_minutes integer not null default 480,
  add column if not exists pricing_fee_percent numeric(7,4) not null default 0,
  add column if not exists pricing_fee_fixed_ils numeric(12,2) not null default 0,
  add column if not exists pricing_reserve_ils numeric(12,2) not null default 0;

alter table public.site_settings drop constraint if exists site_settings_supplier_quote_ttl_check;
alter table public.site_settings add constraint site_settings_supplier_quote_ttl_check
check (supplier_quote_ttl_minutes between 15 and 1440);
alter table public.site_settings drop constraint if exists site_settings_pricing_fee_percent_check;
alter table public.site_settings add constraint site_settings_pricing_fee_percent_check
check (pricing_fee_percent >= 0 and pricing_fee_percent < 100);
alter table public.site_settings drop constraint if exists site_settings_pricing_costs_nonnegative;
alter table public.site_settings add constraint site_settings_pricing_costs_nonnegative
check (pricing_fee_fixed_ils >= 0 and pricing_reserve_ils >= 0);

update public.site_settings
set minimum_profit_ils = coalesce(minimum_profit_ils, 20)
where id = 'primary';

create table if not exists public.supplier_offers (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete cascade,
  provider text not null,
  supplier_id text not null,
  supplier_url text,
  supplier_product_id text not null,
  supplier_sku_id text not null,
  supplier_sku_attr text,
  variant_label text,
  product_price_ils numeric(12,2),
  shipping_price_ils numeric(12,2),
  in_stock boolean,
  stock_quantity integer,
  shipping_available boolean,
  destination_country text not null default 'IL',
  estimated_delivery_days integer,
  equivalence_verified boolean not null default false,
  equivalence_verified_at timestamptz,
  fulfillment_supported boolean not null default false,
  provider_snapshot jsonb not null default '{}'::jsonb,
  last_sync_at timestamptz,
  shipping_last_checked_at timestamptz,
  sync_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint supplier_offers_provider_format check (provider ~ '^[a-z0-9_-]{2,40}$'),
  constraint supplier_offers_supplier_id_format check (supplier_id ~ '^[A-Za-z0-9:_-]{2,160}$'),
  constraint supplier_offers_destination_check check (destination_country ~ '^[A-Z]{2}$'),
  constraint supplier_offers_prices_nonnegative check (
    (product_price_ils is null or product_price_ils >= 0)
    and (shipping_price_ils is null or shipping_price_ils >= 0)
  ),
  constraint supplier_offers_stock_nonnegative check (stock_quantity is null or stock_quantity >= 0),
  constraint supplier_offers_delivery_nonnegative check (estimated_delivery_days is null or estimated_delivery_days >= 0),
  constraint supplier_offers_snapshot_object check (jsonb_typeof(provider_snapshot) = 'object')
);

create unique index if not exists supplier_offers_identity_uidx
on public.supplier_offers(product_id, provider, supplier_id, supplier_product_id, supplier_sku_id, coalesce(supplier_sku_attr, ''));
create index if not exists supplier_offers_optimizer_idx
on public.supplier_offers(product_id, destination_country, equivalence_verified, fulfillment_supported, in_stock, shipping_available);
create index if not exists supplier_offers_sync_idx
on public.supplier_offers(last_sync_at, shipping_last_checked_at);

alter table public.supplier_offers enable row level security;
revoke all privileges on table public.supplier_offers from public, anon, authenticated;
revoke all privileges on sequence public.supplier_offers_id_seq from public, anon, authenticated;
